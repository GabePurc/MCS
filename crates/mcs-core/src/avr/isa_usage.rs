/// An assembler alias that encodes as another instruction.
#[derive(Clone, Copy, Debug)]
pub struct Alias {
    pub name: &'static str,
    /// Canonical lower-case mnemonic this alias encodes as.
    pub of: &'static str,
    pub operands: &'static str,
    pub summary: &'static str,
    pub operation: &'static str,
    pub usage: InsnUsage,
}

const fn al(
    name: &'static str,
    of: &'static str,
    operands: &'static str,
    summary: &'static str,
    operation: &'static str,
    usage: InsnUsage,
) -> Alias {
    Alias { name, of, operands, summary, operation, usage }
}


