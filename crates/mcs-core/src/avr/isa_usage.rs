//! Beginner usage help (what an instruction is for, how to use it, an example) for every
//! canonical AVR mnemonic and the common assembler aliases. Shown in editor hovers and the
//! Instruction Set panel. Source: Microchip "AVR Instruction Set Manual" (DS40002198B).

/// Usage help: when to use an instruction, its operand rules, and a short example.
#[derive(Clone, Copy, Debug)]
pub struct InsnUsage {
    /// 1-3 plain-English sentences: when/why you'd use it, operand rules, typical pitfalls.
    pub help: &'static str,
    /// A short assembly example (1-4 lines, '\n' separated, with `; comments`), avrasm2 syntax.
    pub example: &'static str,
}

const fn u(help: &'static str, example: &'static str) -> InsnUsage {
    InsnUsage { help, example }
}

